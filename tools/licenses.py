#!/usr/bin/env python3
"""Licence texts of every crate built into the given packages (audit X-1).

Usage: python3 tools/licenses.py [-o FILE] cleis-app cleis-server
Reads `cargo metadata` (normal dependencies, this machine's platform) and copies each crate's
LICENSE*, LICENCE*, COPYING* and NOTICE* files; a crate without one is listed with its SPDX
expression so the gap is visible. Fonts and icons are covered in THIRD_PARTY.md and OFL.txt.
"""
import json
import pathlib
import subprocess
import sys

args = sys.argv[1:]
out = sys.stdout
if args[:1] == ["-o"]:
    out = open(args[1], "w", encoding="utf-8", newline="\n")
    args = args[2:]
roots = set(args) or {"cleis-app", "cleis-server"}
host = next(
    l.split(": ", 1)[1]
    for l in subprocess.run(["rustc", "-vV"], capture_output=True, text=True).stdout.splitlines()
    if l.startswith("host: ")
)
meta = json.loads(
    subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", host],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
)
pkgs = {p["id"]: p for p in meta["packages"]}
nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
todo = [i for i, p in pkgs.items() if p["name"] in roots]
seen = set()
while todo:
    i = todo.pop()
    if i in seen:
        continue
    seen.add(i)
    for d in nodes[i]["deps"]:
        if any(k["kind"] in (None, "normal") for k in d["dep_kinds"]):
            todo.append(d["pkg"])

out.write("Licence texts of the software built into Cleis (generated by tools/licenses.py).\n")
missing = []
# The same text (Apache-2.0, MIT with the same holders…) is written once, then referred to.
written = {}
for i in sorted(seen, key=lambda i: (pkgs[i]["name"], pkgs[i]["version"])):
    p = pkgs[i]
    if p["source"] is None:  # Cleis's own crates
        continue
    folder = pathlib.Path(p["manifest_path"]).parent
    files = sorted(
        f
        for f in folder.iterdir()
        if f.is_file()
        and f.name.upper().startswith(("LICENSE", "LICENCE", "COPYING", "NOTICE", "UNLICENSE"))
    )
    out.write(f"\n{'=' * 78}\n{p['name']} {p['version']} — {p.get('license') or 'see below'}\n")
    if p.get("repository"):
        out.write(f"{p['repository']}\n")
    out.write(f"{'=' * 78}\n")
    if not files:
        missing.append(p["name"])
        out.write(f"(no licence file in the package; licence: {p.get('license')})\n")
    for f in files:
        text = f.read_text(encoding="utf-8", errors="replace")
        key = " ".join(text.split())
        if key in written:
            out.write(f"--- {f.name}: same text as {written[key]} ---\n")
            continue
        written[key] = f"{p['name']} {p['version']} ({f.name})"
        out.write(f"\n--- {f.name} ---\n")
        out.write(text)
print(f"{len(seen)} crates, {len(missing)} without a licence file", file=sys.stderr)
